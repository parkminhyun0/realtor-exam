function esc(v='') { return String(v).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])) }
function keyFromPage(page) {
  const bc = page.querySelector('.public-law-breadcrumb')?.textContent || ''
  const part = (bc.match(/PART\s+\d+/)||[''])[0]
  const point = (bc.match(/POINT\s+\d+/)||[''])[0]
  const topic = page.querySelector('.study-section-heading h2')?.textContent?.trim() || ''
  return { key: `${part}|${point}|${topic}`, part, point, topic }
}
function renderSources(sources=[]) {
  return sources.map(s => `<a href="${esc(s.url)}" target="_blank" rel="noreferrer">${esc(s.label)} 원문</a>`).join('')
}
function renderDrills(topic, data) {
  return `<section class="civil-intensive" data-civil-intensive="true"><header class="civil-intensive__head"><div><small>A-GRADE INTENSIVE</small><h3>빈출 함정 집중훈련 · ${esc(topic)}</h3><p>LAW-FIRST 조문을 읽은 뒤 숫자·요건·예외를 O/X로 다시 확인합니다. 아래 문항은 법령 원문과 이미 연결된 판례를 기준으로 구성했습니다.</p></div><div class="civil-intensive__sources">${renderSources(data.sources)}</div></header><div class="civil-intensive__grid">${data.items.map((item,i)=>`<details class="civil-intensive__card"><summary><b>${String(i+1).padStart(2,'0')}</b><span>${esc(item[1])}</span><i>정답 보기</i></summary><div><strong class="${item[0]==='O'?'is-o':'is-x'}">${item[0]}</strong><p>${esc(item[2])}</p></div></details>`).join('')}</div></section>`
}
function findTopicButton(part, point, topic) {
  const page = document.querySelector('.civil-law-page')
  if (!page) return null
  const partDetails = [...page.querySelectorAll('.public-law-nav > details')].find(d => d.querySelector(':scope > summary')?.textContent.includes(part))
  if (!partDetails) return null
  const pointDetails = [...partDetails.querySelectorAll('.civil-nav-point')].find(d => d.querySelector(':scope > summary')?.textContent.includes(point))
  if (!pointDetails) return null
  return [...pointDetails.querySelectorAll('.civil-nav-topic-button')].find(b => b.textContent.includes(topic)) || null
}
function renderRelated(items=[]) {
  return `<section class="civil-intensive-related" data-civil-intensive-related="true"><header><small>CONNECTION MAP</small><h3>이 항목과 같이 풀어야 하는 쟁점</h3></header><div>${items.map((x,i)=>`<button type="button" data-related-index="${i}"><small>${esc(x[0])} · ${esc(x[1])}</small><strong>${esc(x[3])}</strong><span>${esc(x[2])}</span><p>${esc(x[4])}</p></button>`).join('')}</div></section>`
}
function sync() {
  const page = document.querySelector('.civil-law-page')
  if (!page) return
  const { key, topic } = keyFromPage(page)
  page.querySelector('[data-civil-intensive="true"]')?.remove()
  page.querySelector('[data-civil-intensive-related="true"]')?.remove()
  const data = DRILLS[key]
  const related = EXTRA_RELATED[key]
  if (!data && !related) return
  const anchor = page.querySelector('.civil-exam-drills') || page.querySelector('.civil-exam-priority-banner') || page.querySelector('[data-civil-law-part4-first="true"], [data-civil-law-part3-first="true"], [data-civil-law-part2-first="true"], [data-civil-law-part1-first="true"]')
  if (!anchor) return
  let last = anchor
  if (data) {
    const wrap = document.createElement('div'); wrap.innerHTML = renderDrills(topic, data); const node = wrap.firstElementChild
    last.insertAdjacentElement('afterend', node); last = node
  }
  if (related) {
    const wrap = document.createElement('div'); wrap.innerHTML = renderRelated(related); const node = wrap.firstElementChild
    last.insertAdjacentElement('afterend', node)
    node.addEventListener('click', e => {
      const button = e.target.closest('button[data-related-index]'); if (!button) return
      const item = related[Number(button.dataset.relatedIndex)]; const target = findTopicButton(item[0], item[1], item[2])
      if (target) { target.click(); document.querySelector('.civil-law-page .public-law-content')?.scrollIntoView({behavior:'smooth',block:'start'}) }
    })
  }
}
let queued=false
function schedule(){ if(queued) return; queued=true; requestAnimationFrame(()=>{queued=false;sync()}) }
if(typeof document!=='undefined'){
  new MutationObserver(schedule).observe(document.documentElement,{subtree:true,childList:true,characterData:true})
  document.addEventListener('click',e=>{if(e.target.closest('.civil-nav-topic-button,.civil-nav-point summary'))schedule()})
  schedule()
}
